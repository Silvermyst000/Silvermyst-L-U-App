export function applyCabinThemeToDocument(themeMode: CabinThemeMode, isDark: boolean): void {
  if (typeof document === 'undefined') return;
  const cfg = CABIN_THEMES[themeMode] || CABIN_THEMES.royal_purple;
  const pal = isDark ? cfg.darkPalette : cfg.lightPalette;
  const root = document.documentElement;
  root.style.setProperty('--cabin-bg', pal.bg);
  root.style.setProperty('--cabin-bg-secondary', pal.bgSecondary);
  root.style.setProperty('--cabin-surface', pal.surface);
  root.style.setProperty('--cabin-surface-muted', pal.surfaceMuted);
  root.style.setProperty('--cabin-border', pal.border);
  root.style.setProperty('--cabin-text', pal.text);
  root.style.setProperty('--cabin-text-muted', pal.textMuted);
  root.style.setProperty('--cabin-primary', pal.primary);
  root.style.setProperty('--cabin-primary-text', pal.primaryText);
  root.style.setProperty('--cabin-accent', pal.accent);
  root.style.setProperty('--cabin-badge-bg', pal.badgeBg);
  root.style.setProperty('--cabin-badge-text', pal.badgeText);
}

